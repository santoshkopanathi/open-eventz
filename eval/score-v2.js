const fs = require('fs')
const R = JSON.parse(fs.readFileSync('eval/run-v2-results.json', 'utf8')).filter(r => r.v2)
const pct = (a, b) => Math.round(100 * a / b) + '%'
const dist = f => { const c = {}; R.forEach(r => { const v = f(r); c[v] = (c[v] || 0) + 1 }); return c }

console.log('=== GATE 1 — does price_confidence vary? ===')
console.log('  price_confidence :', dist(r => r.v2.price_confidence))
console.log('  kid_confidence   :', dist(r => r.v2.kid_confidence))
console.log('  age_confidence   :', dist(r => r.v2.age_confidence))
console.log('  price value      :', dist(r => r.v2.price))
console.log('  price_basis      :', dist(r => r.v2.price_basis))

console.log('\n=== GATE 2 — calibration: confidence on the events YOU could not determine ===')
const unk = R.filter(r => r.label_price === 'unknown')
const uc = {}; unk.forEach(r => uc[r.v2.price_confidence] = (uc[r.v2.price_confidence] || 0) + 1)
console.log('  n =', unk.length)
console.log('  price_confidence:', uc)
const high = unk.filter(r => r.v2.price_confidence === 'high')
console.log('  HIGH confidence count:', high.length, '  (gate: no more than 4)')
high.forEach(r => console.log('     ! ' + r.n + '. ' + r.title.slice(0, 46) + '  -> ' + r.v2.price + ' / ' + r.v2.price_basis))
console.log('  --- for contrast, on events you COULD determine ---')
const det = R.filter(r => r.label_price !== 'unknown')
const dc = {}; det.forEach(r => dc[r.v2.price_confidence] = (dc[r.v2.price_confidence] || 0) + 1)
console.log('  n =', det.length, '|', dc)

console.log('\n=== GATE 3 — safety: wrongly-free ===')
const wf = R.filter(r => r.label_price === 'paid' && r.v2.price === 'free')
console.log('  events you labelled PAID:', R.filter(r => r.label_price === 'paid').length)
console.log('  WRONGLY-FREE:', wf.length, '  (gate: 0)')
wf.forEach(r => console.log('     ! ' + r.n + '. ' + r.title))
R.filter(r => r.label_price === 'paid').forEach(r =>
  console.log('     paid-labelled: ' + r.title.slice(0, 44).padEnd(46) + 'v2 says ' + r.v2.price + ' (' + r.v2.price_confidence + ')'))

console.log('\n=== GATE 4 — kid-relevance ===')
const wasHidden = R.filter(r => r.label_kid === 'yes' && r.v1.kid_relevant === false)
const nowShown = wasHidden.filter(r => r.v2.kid_relevant === true)
console.log('  you said YES, v1 hid them:', wasHidden.length)
console.log('  ...v2 now shows:', nowShown.length, '  (gate: all of them)')
wasHidden.forEach(r => console.log('     ' + (r.v2.kid_relevant ? 'OK  ' : 'MISS') + ' ' + r.title.slice(0, 48).padEnd(50) + JSON.stringify(r.v2.age_buckets)))
const saidNo = R.filter(r => r.label_kid === 'no')
const leaked = saidNo.filter(r => r.v2.kid_relevant === true)
console.log('\n  you said NO:', saidNo.length, '| v2 shows any of them:', leaked.length, '  (gate: 0)')
saidNo.forEach(r => console.log('     ' + (r.v2.kid_relevant ? 'LEAK' : 'OK  ') + ' ' + r.title))
