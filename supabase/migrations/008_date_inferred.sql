-- date_inferred: this occurrence's DATE was derived by us, not published by the source (v1.4)
-- Run this in the Supabase SQL Editor BEFORE deploying the rebuilt Kaleidoscope connector.
--
-- WHY. Kaleidoscope Park rebuilt their site in October 2026 and the events API we used is
-- gone. The replacement publishes one page per PROGRAM with only the NEXT occurrence in
-- machine-readable form; further dates are written into the marketing copy, and one program
-- (SaturYAY) publishes no list at all -- just "Every Saturday · through Dec 18, 2027".
--
-- For that one program we generate a short horizon of Saturdays so a parent browsing two
-- weeks out can see it. Those rows are different in kind from every other row we store:
-- nobody published them. This column records that difference, and three things depend on it:
--
--   1. SITEMAP + RICH DATA. Inferred rows are excluded from the sitemap and emit no Event
--      JSON-LD. Telling Google "there is an event at 10 AM on 9 January" in machine-readable
--      form, when nobody said so, is a claim we cannot back.
--   2. HONESTY IN THE UI. The detail page says the date came from the organiser's stated
--      weekly schedule rather than from a published listing.
--   3. MEASUREMENT. In a few months, "how often was an inferred date actually right?" is
--      answerable from data instead of opinion -- the nightly re-read re-anchors on the
--      park's own next date, so every inference is graded within days.
--
-- Backfill: existing rows get false, which is correct -- every row stored before this
-- migration came from a published date.

alter table events
  add column if not exists date_inferred boolean not null default false;

-- Narrow index: inferred rows are a small minority and are filtered on every indexable read.
create index if not exists events_date_inferred_idx on events (date_inferred) where date_inferred;

